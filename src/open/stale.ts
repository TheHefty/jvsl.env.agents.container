/**
 * Whether a project's generated configuration is older than what this extension
 * would generate (debt
 * a-projects-generated-container-configuration-does-not-follow-an-upgraded-extension).
 *
 * Read at startup in a window that was opened rather than asked to be
 * prepared, which writes nothing. So a stale configuration is **said, with an
 * action that regenerates it**, and nothing is written until it is chosen.
 *
 * Compared by generation, never by version: every release changes the version
 * in the marker, and a notice on every upgrade is a notice nobody reads. A file
 * this extension did not write, cannot read, or did not find says nothing —
 * the open flow already refuses to touch a file that is not its own.
 */
import { REBUILD_FROM_HOST, REBUILD_IN_CONTAINER } from '../build/build.ts'
import { CONFIG_GENERATION, GENERATED_BY, isOurs } from '../build/devcontainer.ts'
import { CONFIG_PATH } from './open.ts'

export type Staleness = { stale: false } | { stale: true; message: string; wroteWith: string; generation: number }

export function staleness(existing: string | null, extensionVersion: string): Staleness {
  if (existing === null || !isOurs(existing)) return { stale: false }
  let marker: Record<string, unknown>
  try {
    marker = (JSON.parse(existing) as Record<string, Record<string, unknown>>)[GENERATED_BY] ?? {}
  } catch {
    return { stale: false }
  }
  const generation = typeof marker['generation'] === 'number' ? marker['generation'] : 1
  if (generation >= CONFIG_GENERATION) return { stale: false }
  const wroteWith = typeof marker['extension'] === 'string' ? marker['extension'] : 'an older version'
  return {
    stale: true,
    wroteWith,
    generation,
    message:
      `This project's \`${CONFIG_PATH}\` was generated by the extension ${wroteWith}, and ${extensionVersion} ` +
      `generates it differently — the container does not have what this version would give it (the host's ` +
      `timezone, for one). Choose Regenerate to rewrite it; if the project already has a container, it then asks before recreating it. Nothing has been written.`,
  }
}

/** The project's container, as far as what Regenerate does next needs to know it. */
export type RegeneratedFor = { kind: 'none' } | { kind: 'one'; name: string } | { kind: 'many'; names: string[] }

export type AfterRegenerate =
  | { say: 'reopen' }
  | { say: 'recreate'; message: string; command: string }
  | { say: 'ambiguous'; message: string }

/**
 * What Regenerate does once the configuration is written (debt
 * regenerate-reopens-the-window-but-the-container-keeps-its-old-configuration).
 *
 * **A reopen reattaches to an existing container**, which keeps the
 * configuration it was created with: Regenerate used to end there, and nothing
 * changed until a Rebuild Container by hand. So with a container, the new
 * configuration reaches it only by recreating it, and that is **asked, never
 * done**: recreating ends everything running inside, agent sessions included.
 * The command is Dev Containers' own rebuild for the window it runs in, as
 * after a build (afterBuild). Several containers are never guessed between.
 */
export function afterRegenerate(input: { container: RegeneratedFor; inContainer: boolean }): AfterRegenerate {
  const { container, inContainer } = input
  if (container.kind === 'none') return { say: 'reopen' }
  if (container.kind === 'many') {
    return {
      say: 'ambiguous',
      message: `The configuration was rewritten, but more than one container claims this project (${container.names.join(', ')}), ` +
        'so none is recreated. Remove the ones not in use, then rebuild from Dev Containers.',
    }
  }
  return {
    say: 'recreate',
    message: `The configuration was rewritten, but the container ${container.name} still runs the old configuration. ` +
      'Recreating it ends everything running inside; what is in /config stays on its volume.',
    command: inContainer ? REBUILD_IN_CONTAINER : REBUILD_FROM_HOST,
  }
}
