/**
 * Whether a project's generated configuration is older than what this extension
 * would generate (debt
 * a-projects-generated-container-configuration-does-not-follow-an-upgraded-extension).
 *
 * Read at startup in a window that was opened rather than asked to be
 * prepared, which writes nothing. So a stale configuration is **said, with an
 * action that regenerates it**, and nothing is written until it is chosen.
 *
 * Compared by generation, never by version: every release changes the version
 * in the marker, and a notice on every upgrade is a notice nobody reads. A file
 * this extension did not write, cannot read, or did not find says nothing —
 * the open flow already refuses to touch a file that is not its own.
 */
import { CONFIG_GENERATION, GENERATED_BY, isOurs } from '../build/devcontainer.ts'
import { CONFIG_PATH } from './open.ts'

export type Staleness = { stale: false } | { stale: true; message: string; wroteWith: string; generation: number }

export function staleness(existing: string | null, extensionVersion: string): Staleness {
  if (existing === null || !isOurs(existing)) return { stale: false }
  let marker: Record<string, unknown>
  try {
    marker = (JSON.parse(existing) as Record<string, Record<string, unknown>>)[GENERATED_BY] ?? {}
  } catch {
    return { stale: false }
  }
  const generation = typeof marker['generation'] === 'number' ? marker['generation'] : 1
  if (generation >= CONFIG_GENERATION) return { stale: false }
  const wroteWith = typeof marker['extension'] === 'string' ? marker['extension'] : 'an older version'
  return {
    stale: true,
    wroteWith,
    generation,
    message:
      `This project's \`${CONFIG_PATH}\` was generated by the extension ${wroteWith}, and ${extensionVersion} ` +
      `generates it differently — the container does not have what this version would give it (the host's ` +
      `timezone, for one). Choose Regenerate to rewrite it and reopen in the container. Nothing has been written.`,
  }
}
